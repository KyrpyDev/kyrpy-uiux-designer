# ==============================================================================
# Kyrpy UI/UX Designer — One-Click Local Installer (Windows PowerShell)
# ==============================================================================
# Usage:
#   .\installer.ps1
#   .\installer.ps1 -NonInteractive -NoStart
# ==============================================================================

param(
  [switch]$NonInteractive = $false,
  [switch]$NoStart = $false
)

$ErrorActionPreference = "Stop"
$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $RootDir

Write-Host ""
Write-Host "======================================================================" -ForegroundColor Cyan
Write-Host "  Kyrpy UI/UX App Designer — One-Click Local Installer (PowerShell)" -ForegroundColor Cyan
Write-Host "======================================================================" -ForegroundColor Cyan
Write-Host ""

# 1. Verify Node.js >= 22
if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Write-Error "Node.js is not installed. Please install Node.js v22 or newer (https://nodejs.org)."
  exit 1
}

$NodeVer = (node -v).TrimStart('v')
$NodeMajor = [int]($NodeVer.Split('.')[0])
if ($NodeMajor -lt 22) {
  Write-Error "Node.js v22+ is required (found v$NodeVer) because Kyrpy UI/UX Designer uses built-in node:sqlite."
  exit 1
}
Write-Host "[OK]   Detected Node.js v$NodeVer" -ForegroundColor Green

# 2. Configure .env
$EnvFile = Join-Path $RootDir ".env"
$Port = "5180"
$HostAddr = "127.0.0.1"
$AppMode = "dev"
$BypassAuth = "true"
$PgSyncEnabled = "false"
$PgHost = ""
$PgPort = "5432"
$PgUser = ""
$PgPassword = ""
$PgDatabase = "postgres"
$PgSchema = "uiux_designer"
$PgSsl = "false"

if (-not $NonInteractive) {
  Write-Host "----------------------------------------------------------------------"
  Write-Host "  Runtime Mode (dev = bypass login/register | release = login/register protected)"
  Write-Host "----------------------------------------------------------------------"
  $InputMode = Read-Host "Select runtime mode [dev/release] (default: dev)"
  if ($InputMode -and $InputMode.Trim().ToLower() -eq "release") {
    $AppMode = "release"
    $BypassAuth = "false"
  }

  $InputPort = Read-Host "Local HTTP port [5180]"
  if ($InputPort) { $Port = $InputPort.Trim() }

  $WantPg = Read-Host "Configure server-side PostgreSQL connection? [y/N]"
  if ($WantPg -match "^[Yy]") {
    $PgHost = (Read-Host "  PG_HOST (leave empty for local-only SQLite mode)").Trim()
    if ($PgHost) {
      $InPgPort = Read-Host "  PG_PORT [5432]"
      if ($InPgPort) { $PgPort = $InPgPort.Trim() }
      $InPgUser = Read-Host "  PG_USER [postgres]"
      if ($InPgUser) { $PgUser = $InPgUser.Trim() } else { $PgUser = "postgres" }
      $PgPassword = Read-Host "  PG_PASSWORD"
      $InPgDb = Read-Host "  PG_DATABASE [postgres]"
      if ($InPgDb) { $PgDatabase = $InPgDb.Trim() }
      $InPgSchema = Read-Host "  PG_SCHEMA [uiux_designer]"
      if ($InPgSchema) { $PgSchema = $InPgSchema.Trim() }
      $PgSyncEnabled = "true"
    }
  }
}

$EnvContent = @"
# Generated by Kyrpy UI/UX Designer installer.ps1
PORT=$Port
HOST=$HostAddr
APP_MODE=$AppMode
BYPASS_AUTH=$BypassAuth
DEFAULT_ADMIN_USER=admin
DEFAULT_ADMIN_PASS=admin
PG_SYNC_ENABLED=$PgSyncEnabled
PG_HOST=$PgHost
PG_PORT=$PgPort
PG_USER=$PgUser
PG_PASSWORD=$PgPassword
PG_DATABASE=$PgDatabase
PG_SCHEMA=$PgSchema
PG_SSL=$PgSsl
"@

Set-Content -Path $EnvFile -Value $EnvContent -Encoding UTF8
Write-Host "[OK]   Wrote .env configuration (APP_MODE=$AppMode, PG_SYNC_ENABLED=$PgSyncEnabled)" -ForegroundColor Green

# 3. Ensure default admin / admin account is seeded
Write-Host "[INFO] Ensuring default startup account (username: admin / password: admin)..." -ForegroundColor Cyan
Push-Location (Join-Path $RootDir "src")
node --disable-warning=ExperimentalWarning --input-type=module -e "import { buildContainer } from './composition-root.js'; const c = buildContainer({ dbFile: './data/designer.db', syncEnabled: false }); c.auth.ensureDefaultAdmin(); c.db.close();"
Write-Host "[OK]   Default startup account ready -> Username: admin | Password: admin" -ForegroundColor Green

# 4. Run test suite
Write-Host "[INFO] Running verification test suite..." -ForegroundColor Cyan
npm test
Pop-Location

# 5. Launch runner if requested
if (-not $NoStart) {
  & (Join-Path $RootDir "runner.ps1") start
}
