# ==============================================================================
# Kyrpy UI/UX Designer - Installer (Windows PowerShell 5.1+ / PowerShell 7)
# ==============================================================================
# Optional: .\runner.ps1 alone prepares and starts a fresh clone with the defaults.
# The installer asks a few questions, writes .env, prepares the environment
# (packages, local database), runs the tests and starts the server.
#
#   .\installer.ps1                    Ask the questions
#   .\installer.ps1 -NonInteractive    No questions: keep an existing .env, else write the defaults
#   .\installer.ps1 -NoStart           Do not start the server at the end
#   .\installer.ps1 -SkipTests         Do not run the test suite
#   .\installer.ps1 -Reconfigure       Ask again although .env exists (the old file is kept as .env.bak)
#
# Database: the server always works on its local SQLite file. PostgreSQL is an optional
# sync target of the superadmin's "Database sync" tool; it is off unless you enter a host here.
# ==============================================================================

param(
  [switch]$NonInteractive = $false,
  [switch]$NoStart = $false,
  [switch]$SkipTests = $false,
  [switch]$Reconfigure = $false
)

$ErrorActionPreference = "Stop"
$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$EnvFile = Join-Path $RootDir ".env"
$Runner = Join-Path $RootDir "runner.ps1"
if (-not (Test-Path $Runner)) { Write-Host "[ERR]  runner.ps1 is missing next to installer.ps1." -ForegroundColor Red; exit 1 }
if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Write-Host "[ERR]  Node.js is not installed. Install Node.js 22.13 or newer (https://nodejs.org)." -ForegroundColor Red; exit 1 }
Write-Host "[OK]   Detected Node.js $(& node -v)" -ForegroundColor Green

$Port = "5180"; $AppMode = "release"; $Bypass = "false"; $PgSync = "false"; $LocalOnly = "true"
$PgHost = ""; $PgPort = "5432"; $PgUser = "postgres"; $PgPassword = ""; $PgDatabase = "kyrpy-uiux-designer-db"; $PgAdminDb = "postgres"

function Ask([string]$Q, [string]$Default) { $a = Read-Host $Q; if ([string]::IsNullOrWhiteSpace($a)) { return $Default } else { return $a.Trim() } }
function Test-Reachable([string]$H, [int]$P) {
  $c = New-Object System.Net.Sockets.TcpClient
  try { $r = $c.BeginConnect($H, $P, $null, $null); if (-not $r.AsyncWaitHandle.WaitOne(4000)) { return $false }; $c.EndConnect($r); return $true } catch { return $false } finally { $c.Close() }
}
function Write-Env {
  $lines = @(
    "# Kyrpy UI/UX Designer - settings (generated by installer.ps1; edit freely)",
    "PORT=$Port",
    "# release = sign-in required | dev = no sign-in, every visitor acts as the superadmin",
    "APP_MODE=$AppMode", "BYPASS_AUTH=$Bypass",
    "# The server always works on its local SQLite database. PostgreSQL is an optional sync target",
    "# (superadmin ""Database sync"" tool): PG_SYNC_ENABLED=true plus the PG* values switch it on.",
    "PG_SYNC_ENABLED=$PgSync", "LOCAL_ONLY=$LocalOnly",
    "PGHOST=$PgHost", "PGPORT=$PgPort", "PGUSER=$PgUser", "PGPASSWORD=$PgPassword", "PGDATABASE=$PgDatabase", "PGADMINDB=$PgAdminDb"
  )
  [System.IO.File]::WriteAllLines($EnvFile, $lines, (New-Object System.Text.UTF8Encoding($false)))
}

if ((Test-Path $EnvFile) -and -not $Reconfigure) {
  Write-Host "[INFO] Keeping the existing .env (use -Reconfigure to answer the questions again)."
} else {
  if (Test-Path $EnvFile) { Copy-Item $EnvFile "$EnvFile.bak" -Force; Write-Host "[INFO] Old settings kept as .env.bak" }
  if (-not $NonInteractive) {
    Write-Host "Runtime mode:  release = sign-in required  |  dev = no sign-in, every visitor acts as the superadmin (local use only)"
    if ((Ask "Runtime mode [release/dev] (default: release)" "release").ToLower() -eq "dev") { $AppMode = "dev"; $Bypass = "true" }
    while ($true) {
      $Port = Ask "Local HTTP port [5180]" "5180"; $n = 0
      if ([int]::TryParse($Port, [ref]$n) -and $n -ge 1 -and $n -le 65535) { break }
      Write-Host "[WARN] Enter a port number between 1 and 65535." -ForegroundColor Yellow
    }
    Write-Host ""
    Write-Host "The server works on its local SQLite database. A PostgreSQL server is only needed if the superadmin"
    Write-Host "wants to copy the whole database to it (or back) with the ""Database sync"" tool. Press Enter to skip."
    if ((Ask "Set up a PostgreSQL sync target? [y/N]" "N") -match "^[Yy]") {
      $PgHost = Ask "  PGHOST (empty = skip)" ""
      if ($PgHost) {
        $PgPort = Ask "  PGPORT [5432]" "5432"
        $PgUser = Ask "  PGUSER [postgres]" "postgres"
        $sec = Read-Host "  PGPASSWORD" -AsSecureString
        $PgPassword = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec))
        $PgDatabase = Ask "  PGDATABASE [kyrpy-uiux-designer-db]" "kyrpy-uiux-designer-db"
        $PgAdminDb = Ask "  PGADMINDB [postgres]" "postgres"
        $pn = 0
        if ([int]::TryParse($PgPort, [ref]$pn) -and (Test-Reachable $PgHost $pn)) { $PgSync = "true"; $LocalOnly = "false"; Write-Host "[OK]   PostgreSQL answers: the superadmin's Database sync tool is switched on." -ForegroundColor Green }
        else { Write-Host "[WARN] No answer from ${PgHost}:$PgPort. The values are saved, but sync stays off (PG_SYNC_ENABLED=false)." -ForegroundColor Yellow }
      }
    }
  }
  Write-Env
  Write-Host "[OK]   Wrote .env (APP_MODE=$AppMode, PORT=$Port, PG_SYNC_ENABLED=$PgSync)." -ForegroundColor Green
}

Write-Host "[INFO] Preparing the environment ..."
& $Runner setup
if (-not $?) { Write-Host "[ERR]  Environment setup failed." -ForegroundColor Red; exit 1 }

if (-not $SkipTests) {
  Write-Host "[INFO] Running the test suite (about a minute; skip with -SkipTests) ..."
  Push-Location (Join-Path $RootDir "src")
  try {
    $env:PG_SYNC_ENABLED = "false"; $env:LOCAL_ONLY = "true"
    & npm test *> (Join-Path $RootDir "installer-tests.log")
    if ($LASTEXITCODE -eq 0) { Write-Host "[OK]   All tests passed." -ForegroundColor Green; Remove-Item (Join-Path $RootDir "installer-tests.log") -ErrorAction SilentlyContinue }
    else { Write-Host "[WARN] Some tests failed (details: installer-tests.log). The server can still be started." -ForegroundColor Yellow }
  } finally { Pop-Location; Remove-Item Env:PG_SYNC_ENABLED, Env:LOCAL_ONLY -ErrorAction SilentlyContinue }
}

if (-not $NoStart) { & $Runner start } else { Write-Host "[OK]   Done. Start the server with: .\runner.ps1 start" -ForegroundColor Green }
