export function themesCss(themes) {
  const vars = themes.map(t => `[data-theme="${t.key}"] {\n${themeCssVars(t)}\n}`).join('\n\n');
  const show = themes.map(t => `html[data-theme="${t.key}"] .ud-device svg[data-theme="${t.key}"] { display: block; }`).join('\n');
  const bg = themes.map(t => `html[data-theme="${t.key}"] body { background: ${resolveTokens('{{bg}}', t.tokens)}; color: ${resolveTokens('{{text}}', t.tokens)}; }`).join('\n');
  return `/* Generated by Kyrpy UI/UX Designer. One block of CSS variables per theme; tokens are named --ud-<token>. */\n${vars}\n\n${bg}\n\n.ud-device svg { display: none; width: 100%; height: auto; }\n${show}\n`;
}

