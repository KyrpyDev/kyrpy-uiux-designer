const pct = (v, total) => `${Math.round((v / total) * 10000) / 100}%`;

/** One screen page: all theme variants inline (only the active theme is displayed), links, hotspots, dev notes. */
/** The pieces of one screen page (also used by the single-file project viewer): device markup, overlays (popups/drawers), link list. */
export function screenParts({ screen, inlineSvgs, links, components, actions = [], overlays = [] }) {
  const W = screen.width, H = screen.height;
  const pos = b => `left:${pct(b.x, W)};top:${pct(b.y, H)};width:${pct(b.w, W)};height:${pct(b.h, H)}`;
  const sameBox = (a, b) => ['x', 'y', 'w', 'h'].every(k => Math.abs(a[k] - b[k]) < 0.5);
  // an element action that routes to a screen replaces the workflow link hotspot on the same element
  const dup = l => actions.some(a => a.type === 'screen' && a.to === l.to && sameBox(a.hotspot, l.hotspot));
  const act = actions.map(a => {
    const trigAttr = a.trigger && a.trigger !== 'click' ? ` data-trigger="${esc(a.trigger)}"` : '';
    const common = `style="${pos(a.hotspot)}" aria-label="${esc(a.name)}" title="${esc(a.name)}" data-action="${esc(a.type)}"${trigAttr}`;
    if (a.type === 'screen') return `<a class="ud-hotspot" href="${esc(a.to)}.html" data-ud-href="${esc(a.to)}.html" ${common}></a>`;
    if (a.overlay) return `<button type="button" class="ud-hotspot" data-ud-open="${esc(a.overlay)}" aria-haspopup="dialog" ${common}></button>`;
    if (a.type === 'animate' || a.type === 'toggle') return `<button type="button" class="ud-hotspot" data-ud-toggle ${common}></button>`;
    return `<button type="button" class="ud-hotspot" data-ud-back ${common}></button>`;
  }).join('\n      ');
  const ov = overlays.map(o => `<div class="ud-overlay ud-${o.kind}${o.side ? ` ud-from-${o.side}` : ''}" id="${esc(o.id)}" role="dialog" aria-modal="true" aria-label="${esc(o.label)}" hidden>
  <div class="ud-scrim" data-ud-close></div>
  <div class="ud-panel" style="--ud-panel-w:${o.width}px">
    <button type="button" class="ud-close" data-ud-close aria-label="Close">✕</button>
    <div class="ud-scroll"><div class="ud-device" style="--ud-device-w:${o.width}px">${o.svgs.join('\n      ')}</div></div>
  </div>
</div>`).join('\n');
  const hot = links.filter(l => l.hotspot && !dup(l)).map(l =>
    `<a class="ud-hotspot" href="${esc(l.to)}.html" style="left:${pct(l.hotspot.x, W)};top:${pct(l.hotspot.y, H)};width:${pct(l.hotspot.w, W)};height:${pct(l.hotspot.h, H)}" aria-label="${esc(l.name)}" title="${esc(l.name)}" data-trigger="${esc(l.trigger)}"></a>`).join('\n      ');
  const ctl = components.filter(c => ['button', 'a'].includes(c.htmlTag)).map(c =>
    `<${c.htmlTag === 'a' ? 'a href="#"' : 'button type="button"'} class="ud-ctl" style="left:${pct(c.box.x, W)};top:${pct(c.box.y, H)};width:${pct(c.box.w, W)};height:${pct(c.box.h, H)}" aria-label="${esc(c.name)}"></${c.htmlTag === 'a' ? 'a' : 'button'}>`).join('\n      ');
  const linkList = links.map(l => `<a href="${esc(l.to)}.html"><strong>${esc(l.name || l.to)}</strong><small>→ ${esc(l.to)} · ${esc(l.trigger)}</small></a>`).join('\n        ') || '<small>No outgoing links.</small>';
  const device = `<div class="ud-device" style="--ud-device-w:${W}px" id="${esc(screen.key)}">
    ${inlineSvgs.join('\n    ')}
    ${hot}
    ${act}
    ${ctl}
  </div>`;
  return { device, overlays: ov, linkList };
}

