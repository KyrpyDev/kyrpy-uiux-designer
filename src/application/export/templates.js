export function appJs(menuRuntime = 'function bindMenus() {}', repeaterRuntime = 'function bindRepeaters() {} function bindRepeaterScroll() {}') {
  return `/* Generated. Plain-JS twin of ts/app.ts (same behaviour, no build step needed). */
(function () {
  'use strict';
  var themes = window.UD_THEMES || [];
  var root = document.documentElement;
  var saved = null;
  try { saved = localStorage.getItem('ud-theme'); } catch (e) {}
  if (saved && themes.some(function (t) { return t.key === saved; })) root.setAttribute('data-theme', saved);

  var select = document.getElementById('ud-theme');
  if (select) {
    themes.forEach(function (t) { var o = document.createElement('option'); o.value = t.key; o.textContent = t.name; select.appendChild(o); });
    select.value = root.getAttribute('data-theme') || (themes[0] && themes[0].key) || '';
    select.addEventListener('change', function () {
      root.setAttribute('data-theme', select.value);
      try { localStorage.setItem('ud-theme', select.value); } catch (e) {}
    });
  }

  // click-triggered animations: toggle .ud-on on the animated element that was clicked
  document.addEventListener('click', function (ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest('[class*="ud-e"]') : null;
    if (t) t.classList.toggle('ud-on');
  });

  // popups, drawers, inline elements and toolbars: hotspots carry data-ud-open="<overlay id>" and optional data-trigger
  var openOverlay = null, returnTo = null;
  function closeOverlay() {
    if (!openOverlay) return false;
    openOverlay.hidden = true; openOverlay = null;
    if (returnTo && returnTo.focus) returnTo.focus();
    returnTo = null; return true;
  }
  function triggerHotspot(t) {
    if (!t) return;
    if (t.hasAttribute('data-ud-close')) { closeOverlay(); return; }
    if (t.hasAttribute('data-ud-back')) { history.back(); return; }
    if (t.hasAttribute('data-ud-toggle')) { t.classList.toggle('ud-on'); return; }
    var href = t.getAttribute('data-ud-href');
    if (href) { location.href = href; return; }
    var o = document.getElementById(t.getAttribute('data-ud-open'));
    if (!o) return;
    closeOverlay(); o.hidden = false; openOverlay = o; returnTo = t;
    var c = o.querySelector('.ud-close'); if (c) c.focus();
  }
  document.addEventListener('click', function (ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest('[data-ud-open], [data-ud-close], [data-ud-back], [data-ud-toggle], [data-ud-href]') : null;
    if (!t) return;
    var trig = t.getAttribute('data-trigger') || 'click';
    if (trig === 'click' || t.hasAttribute('data-ud-close')) triggerHotspot(t);
  });
  ['dblclick', 'mouseover', 'mouseleave', 'mousedown', 'mouseup', 'dragstart', 'drop', 'focus'].forEach(function (domEv) {
    var mapTrig = domEv === 'mouseup' ? 'release' : (domEv === 'dragstart' ? 'drag' : domEv);
    document.addEventListener(domEv, function (ev) {
      var t = ev.target && ev.target.closest ? ev.target.closest('[data-trigger="' + mapTrig + '"]') : null;
      if (t) triggerHotspot(t);
    });
  });

  // keyboard: Alt+Left goes back, Escape closes an open popup/drawer, else returns to the index
  document.addEventListener('keydown', function (ev) {
    if (ev.altKey && ev.key === 'ArrowLeft') history.back();
    if (ev.key === 'Escape') { if (closeOverlay()) return; if (document.body.dataset.screen) location.href = '../index.html'; }
  });

  // index page: filter cards
  var search = document.getElementById('ud-search');
  if (search) search.addEventListener('input', function () {
    var q = search.value.toLowerCase();
    document.querySelectorAll('.ud-card').forEach(function (c) { c.style.display = (c.getAttribute('data-search') || '').indexOf(q) >= 0 ? '' : 'none'; });
  });

  // button menus (popup / rotating): the same runtime the designer preview uses
  var bindMenus = ${menuRuntime};
  bindMenus(document, { onAction: function (a) { if (a.target) location.href = a.target + '.html'; else document.dispatchEvent(new CustomEvent('ud-menu-action', { detail: a })); } });

  // repeater containers: each .ud-repeater holds its template once; repeat it itemCount times with its layout / 2D-3D effect
  ${repeaterRuntime}
  bindRepeaters(document);
  bindRepeaterScroll(document);   // wheel / drag inside a repeater scrolls its copies

  // hotspots: navigate on click (they are real links; this adds the click animation hook for the target element)
  document.querySelectorAll('.ud-hotspot').forEach(function (a) { a.addEventListener('click', function () { a.classList.add('ud-on'); }); });
})();
`;
}

