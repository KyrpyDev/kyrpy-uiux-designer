/**
 * Web target adapter (pure): turns rendered icon SVGs + tokens into ready-to-import web files.
 *   icons.sprite.svg   <symbol id="icon-<key>"> per icon, ids made unique per symbol
 *   index.ts           typed icon keys and sprite ids
 * (tokens.css / tokens.ts come from DesignQueryService.tokens)
 */
import { suffixIds } from '../../domain/svg.js';

const esc = s => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const firstDefs = svg => /<defs>[\s\S]*?<\/defs>/.exec(String(svg))?.[0] || null;

/**
 * One rendered SVG document → a <symbol>; ids (also inside <style>) are suffixed with the icon key.
 * `sharedDefs`: a <defs> block hoisted to the sprite root; it is removed here and its ids stay global.
 */
export function svgToSymbol(svgText, key, { sharedDefs = null } = {}) {
  let svg = String(svgText).replace(/<\?xml[^>]*\?>\s*/, '');
  if (sharedDefs) svg = svg.replace(sharedDefs, '');
  const open = /<svg\b([^>]*)>/.exec(svg);
  if (!open) return '';
  const viewBox = /\sviewBox="([^"]+)"/.exec(open[1])?.[1] || '0 0 24 24';
  const ids = [...svg.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]);
  let inner = svg.slice(open.index + open[0].length, svg.lastIndexOf('</svg>'));
  inner = suffixIds(inner, key);
  if (ids.length) {
    const alt = new RegExp(`#(${ids.map(esc).join('|')})(?![\\w-])`, 'g');
    inner = inner.replace(/<style>([\s\S]*?)<\/style>/g, (_, css) => `<style>${css.replace(alt, `#$1-${key}`)}</style>`);
  }
  const label = /\saria-label="([^"]*)"/.exec(open[1])?.[1];
  return `<symbol id="icon-${key}" viewBox="${viewBox}"${label ? ` aria-label="${label}"` : ''}>${inner}</symbol>`;
}

/*
 * The sprite root is hidden with zero size, NOT display:none: Chrome does not paint gradients/filters
 * defined inside a display:none SVG, and every symbol references the shared style defs.
 */

/** The <defs> block most icons share (the style's gradients/filters), hoisted once; null if none repeats. */
export function sharedDefsOf(entries) {
  const counts = new Map();
  for (const e of entries) { const d = firstDefs(e.svg); if (d) counts.set(d, (counts.get(d) || 0) + 1); }
  const [best, n] = [...counts.entries()].sort((a, b) => b[1] - a[1])[0] || [null, 0];
  return n >= 2 ? best : null;
}

export function spriteSvg(entries) {
  const shared = sharedDefsOf(entries);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated by kyrpy-uiux-mcp; do not edit -->\n<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute;width:0;height:0;overflow:hidden" aria-hidden="true">\n${shared ? `${shared}\n` : ''}${entries.map(e => svgToSymbol(e.svg, e.key, { sharedDefs: shared })).join('\n')}\n</svg>\n`;
}

export function iconIndexTs(style, entries) {
  const lines = entries.map(e => `  ${JSON.stringify(e.key)}: { id: ${JSON.stringify(`icon-${e.key}`)}, uid: ${JSON.stringify(e.uid)}, contentHash: ${JSON.stringify(e.contentHash)} },`);
  return `// generated by kyrpy-uiux-mcp for style "${style}"; do not edit
// Usage: <svg aria-hidden="true"><use href={\`\${spriteUrl}#\${icons['<key>'].id}\`} /></svg>
export const style = ${JSON.stringify(style)};
export const icons = {
${lines.join('\n')}
} as const;
export type IconKey = keyof typeof icons;
export const iconKeys = Object.keys(icons) as IconKey[];
`;
}

/**
 * react-tsx adapter: a typed <Icon> component over the style's sprite. Deterministic text, so a re-pull of
 * an unchanged design produces no diff. The sprite URL defaults to `/<root>/<style>/icons.sprite.svg`
 * and can be changed once with setIconSpriteUrl() (for example to a bundler-imported asset URL).
 */
export function reactIconTsx(style, entries, { root = 'uiux' } = {}) {
  const keys = entries.map(e => JSON.stringify(e.key)).join(' | ') || 'never';
  return `// generated by kyrpy-uiux-mcp (adapter react-tsx) for style "${style}"; do not edit
// generated-from: ${entries.map(e => `${e.uid}@${e.contentHash.slice(0, 12)}`).join(', ') || 'no icons'}
import type { SVGProps } from 'react';

export type IconName = ${keys};
export const iconNames: readonly IconName[] = [${entries.map(e => JSON.stringify(e.key)).join(', ')}];

let spriteUrl = ${JSON.stringify(`/${root}/${style}/icons.sprite.svg`)};
/** Points every <Icon> at another sprite URL (call once at start-up). */
export function setIconSpriteUrl(url: string): void { spriteUrl = url; }

export type IconProps = { name: IconName; size?: number | string; title?: string } & Omit<SVGProps<SVGSVGElement>, 'name'>;

/** Renders one icon from the sprite. Decorative unless \`title\` is given. */
export function Icon({ name, size = 24, title, ...rest }: IconProps) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" role={title ? 'img' : undefined} aria-hidden={title ? undefined : true} focusable="false" {...rest}>
      {title ? <title>{title}</title> : null}
      <use href={\`\${spriteUrl}#icon-\${name}\`} />
    </svg>
  );
}
`;
}

/** react-tsx adapter index: re-exports the component and the tokens of the style. */
export function reactIndexTs(style) {
  return `// generated by kyrpy-uiux-mcp (adapter react-tsx) for style "${style}"; do not edit
export * from './Icon';
export { tokens } from './tokens';
export type { TokenName } from './tokens';
`;
}
