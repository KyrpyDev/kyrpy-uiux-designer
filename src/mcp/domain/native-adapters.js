/**
 * Native target adapters (pure, deterministic): Flutter (Dart), Jetpack Compose (Kotlin) and SwiftUI.
 * Each produces a tokens file (colors as native color values, numbers and strings as constants) and an
 * icon catalog pointing at the style's SVG files, which the bundle ships next to it under icons/.
 * The same design always gives the same text, so a re-pull of an unchanged design causes no diff.
 */

/** Parses #rgb, #rgba, #rrggbb, #rrggbbaa, rgb() and rgba(); null for anything else (gradients, names …). */
export function parseColor(value) {
  const v = String(value ?? '').trim();
  let m = /^#([0-9a-f]{3,4}|[0-9a-f]{6}|[0-9a-f]{8})$/i.exec(v);
  if (m) {
    let h = m[1];
    if (h.length <= 4) h = [...h].map(c => c + c).join('');
    const n = i => parseInt(h.slice(i, i + 2), 16);
    return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 };
  }
  m = /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+%?)\s*)?\)$/i.exec(v);
  if (m) {
    const a = m[4] === undefined ? 1 : m[4].endsWith('%') ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
    const c = x => Math.max(0, Math.min(255, Math.round(parseFloat(x))));
    return { r: c(m[1]), g: c(m[2]), b: c(m[3]), a: Math.max(0, Math.min(1, a)) };
  }
  return null;
}

const RESERVED = new Set(['class', 'const', 'default', 'enum', 'extension', 'in', 'is', 'new', 'null', 'object', 'return', 'static', 'super', 'switch', 'this', 'true', 'false', 'var', 'val', 'fun', 'when', 'let', 'func', 'case', 'import', 'package', 'protocol', 'struct', 'self', 'Self', 'init', 'as', 'do', 'for', 'if', 'else', 'while', 'try', 'catch', 'throw', 'void', 'with', 'final', 'operator', 'typealias', 'interface']);

/** "glass-surface" / "glass_surface" / "glassSurface" → glassSurface (a valid identifier in all three languages). */
export function identifier(name, { upper = false } = {}) {
  const parts = String(name).replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^A-Za-z0-9]+/).filter(Boolean);
  let id = parts.map((p, i) => (i === 0 && !upper ? p.toLowerCase() : p[0].toUpperCase() + p.slice(1).toLowerCase())).join('') || 'item';
  if (/^\d/.test(id)) id = `${upper ? 'N' : 'n'}${id}`;
  if (RESERVED.has(id)) id = `${id}Value`;
  return id;
}

const hex2 = n => n.toString(16).padStart(2, '0').toUpperCase();
const argb = c => `0x${hex2(Math.round(c.a * 255))}${hex2(c.r)}${hex2(c.g)}${hex2(c.b)}`;
const num = v => (typeof v === 'number' && Number.isFinite(v)) || (typeof v === 'string' && /^-?\d+(\.\d+)?$/.test(v.trim()));
const q = s => JSON.stringify(String(s));
const fix = n => Number(Number(n).toFixed(4));
const cap = id => id[0].toUpperCase() + id.slice(1);

/** Splits flat tokens into colors / numbers / strings, sorted by name, with unique identifiers. */
export function classifyTokens(tokens = {}) {
  const used = new Set(), out = { colors: [], numbers: [], strings: [] };
  for (const [name, value] of Object.entries(tokens).sort(([a], [b]) => a.localeCompare(b))) {
    if (value === null || typeof value === 'object') continue;
    let id = identifier(name), n = 2;
    while (used.has(id)) id = `${identifier(name)}${n++}`;
    used.add(id);
    const color = parseColor(value);
    if (color) out.colors.push({ name, id, color, value });
    else if (num(value)) out.numbers.push({ name, id, value: Number(value) });
    else out.strings.push({ name, id, value: String(value) });
  }
  return out;
}

const header = (adapter, style, comment = '//') => `${comment} generated by kyrpy-uiux-mcp (adapter ${adapter}) for style "${style}"; do not edit\n`;
const iconIds = entries => { const used = new Set(); return entries.map(e => { let id = identifier(e.key), n = 2; while (used.has(id)) id = `${identifier(e.key)}${n++}`; used.add(id); return { ...e, id }; }); };

/* ---------- Flutter ---------- */

export function flutterTokens(style, tokens) {
  const t = classifyTokens(tokens);
  return `${header('flutter', style)}import 'package:flutter/painting.dart';

/// Design tokens of style "${style}". Use them instead of literal colors and sizes.
class UiuxTokens {
  UiuxTokens._();
  static const String style = ${q(style)};
${t.colors.map(c => `  static const Color ${c.id} = Color(${argb(c.color)}); // ${c.value}`).join('\n')}
${t.numbers.map(n => `  static const double ${n.id} = ${Number.isInteger(n.value) ? `${n.value}.0` : n.value};`).join('\n')}
${t.strings.map(s => `  static const String ${s.id} = ${q(s.value)};`).join('\n')}
}
`;
}

export function flutterIcons(style, entries, { root = 'uiux' } = {}) {
  const icons = iconIds(entries);
  return `${header('flutter', style)}// generated-from: ${entries.map(e => `${e.uid}@${e.contentHash.slice(0, 12)}`).join(', ') || 'no icons'}
// Declare the folder in pubspec.yaml (flutter: assets: - ${root}/${style}/icons/) and draw with flutter_svg:
//   SvgPicture.asset(UiuxIcons.${icons[0]?.id || 'name'}, width: 24, height: 24)

/// Asset paths of the icons of style "${style}".
class UiuxIcons {
  UiuxIcons._();
${icons.map(i => `  static const String ${i.id} = ${q(`${root}/${style}/icons/${i.key}.svg`)};`).join('\n')}
  static const Map<String, String> byKey = {
${icons.map(i => `    ${q(i.key)}: ${i.id},`).join('\n')}
  };
}
`;
}

/* ---------- Jetpack Compose ---------- */

const kotlinPackage = style => `uiux.${String(style).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^(\d)/, 's$1')}`;

export function composeTokens(style, tokens) {
  const t = classifyTokens(tokens);
  return `${header('compose', style)}package ${kotlinPackage(style)}

import androidx.compose.ui.graphics.Color

/** Design tokens of style "${style}". Use them instead of literal colors and sizes. */
object UiuxTokens {
    const val STYLE: String = ${q(style)}
${t.colors.map(c => `    val ${cap(c.id)} = Color(${argb(c.color)}) // ${c.value}`).join('\n')}
${t.numbers.map(n => `    const val ${cap(n.id)}: Float = ${fix(n.value)}f`).join('\n')}
${t.strings.map(s => `    const val ${cap(s.id)}: String = ${q(s.value)}`).join('\n')}
}
`;
}

export function composeIcons(style, entries, { root = 'uiux' } = {}) {
  const icons = iconIds(entries);
  return `${header('compose', style)}// generated-from: ${entries.map(e => `${e.uid}@${e.contentHash.slice(0, 12)}`).join(', ') || 'no icons'}
// Copy icons/ to src/main/assets/${root}/${style}/icons/ (or import them as Vector Assets in Android Studio).
package ${kotlinPackage(style)}

/** Asset paths of the icons of style "${style}" (relative to the app's assets folder). */
enum class UiuxIcon(val key: String, val assetPath: String) {
${icons.map(i => `    ${cap(i.id)}(${q(i.key)}, ${q(`${root}/${style}/icons/${i.key}.svg`)}),`).join('\n')}
    ;
    companion object { fun fromKey(key: String): UiuxIcon? = values().firstOrNull { it.key == key } }
}
`;
}

/* ---------- SwiftUI ---------- */

export function swiftTokens(style, tokens) {
  const t = classifyTokens(tokens);
  const c = x => fix(x / 255);
  return `${header('swiftui', style)}import SwiftUI

/// Design tokens of style "${style}". Use them instead of literal colors and sizes.
enum UiuxTokens {
    static let style = ${q(style)}
${t.colors.map(x => `    static let ${x.id} = Color(.sRGB, red: ${c(x.color.r)}, green: ${c(x.color.g)}, blue: ${c(x.color.b)}, opacity: ${fix(x.color.a)}) // ${x.value}`).join('\n')}
${t.numbers.map(n => `    static let ${n.id}: CGFloat = ${fix(n.value)}`).join('\n')}
${t.strings.map(s => `    static let ${s.id} = ${q(s.value)}`).join('\n')}
}
`;
}

export function swiftIcons(style, entries) {
  const icons = iconIds(entries);
  return `${header('swiftui', style)}// generated-from: ${entries.map(e => `${e.uid}@${e.contentHash.slice(0, 12)}`).join(', ') || 'no icons'}
// Drag icons/*.svg into an asset catalog (asset name = icon key; Preserve Vector Data, Render As: Template).
import SwiftUI

/// The icons of style "${style}".
enum UiuxIcon: String, CaseIterable {
${icons.map(i => `    case ${i.id} = ${q(i.key)}`).join('\n')}

    /// Asset-catalog name of the icon.
    var assetName: String { rawValue }
    /// The icon as a template image (tinted by foregroundStyle).
    var image: Image { Image(assetName).renderingMode(.template) }
}
`;
}
