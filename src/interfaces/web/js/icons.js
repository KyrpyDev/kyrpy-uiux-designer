export function iconForLabel(label = '') {
  const text = String(label).replace(/^[^A-Za-z]+/, ''); // drop leading emoji / symbols
  for (const [re, name] of RULES) if (re.test(text)) return name;
  return 'dot';
}

/** Returns a 16px (default) inline SVG icon element. */
export function iconEl(name, { size = 16, cls = 'ico' } = {}) {
  const key = P[name] ? name : 'dot';
  return h('span', {
    class: cls,
    'aria-hidden': 'true',
    html: `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">${P[key]}</svg>`
  });
}

/**
 * Icon-only button with a hover tooltip (name + explanation).
 * `tip` is the name; pass `desc` for an explanation line and `kbd` for a shortcut.
 */
export function ibtn(icon, tip, onclick, { desc = '', kbd = '', active = false, disabled = false, cls = '', size = 16, dataset, extra = [] } = {}) {
  const shown = [tip, desc, kbd ? `Shortcut: ${kbd}` : ''].filter(Boolean).join('\n');
  return h('button', {
    class: `btn small ib${active ? ' active' : ''}${cls ? ` ${cls}` : ''}`,
    'aria-label': tip, 'data-tip': shown, disabled, onclick, dataset
  }, iconEl(icon, { size }), ...extra);
}
