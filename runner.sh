#!/usr/bin/env bash
# ==============================================================================
# Kyrpy UI/UX Designer — Runner (Linux & macOS)
# ==============================================================================
# Works on a fresh clone: it prepares what the server needs (settings file, local
# database, packages) and then starts it. No installer run is required first.
#
#   ./runner.sh            Start in the background (same as "start")
#   ./runner.sh start      Start in the background with the mode from .env
#   ./runner.sh run        Start in the foreground (Ctrl+C stops it)
#   ./runner.sh dev        (Re)start in Dev mode     — no sign-in, every visitor is the superadmin
#   ./runner.sh release    (Re)start in Release mode — sign-in required
#   ./runner.sh stop       Stop the background server
#   ./runner.sh restart    Stop, then start
#   ./runner.sh status     Is it running, on which port, in which mode
#   ./runner.sh logs       Follow the server log
#   ./runner.sh setup      Prepare the environment only (no start)
#
# Database: the server always works on its local SQLite file (src/data/designer.prod.db,
# created from the bundled sample on first start). PostgreSQL is an optional sync target of
# the superadmin's "Database sync" tool and is OFF unless .env says PG_SYNC_ENABLED=true.
# ==============================================================================

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="$ROOT_DIR/src"
ENV_FILE="$ROOT_DIR/.env"
PID_FILE="$ROOT_DIR/.designer-runner.pid"
LOG_FILE="$ROOT_DIR/designer-runner.log"
NODE_FLAGS=(--disable-warning=ExperimentalWarning)
MIN_NODE_MAJOR=22
MIN_NODE_MINOR=13
SERVE_HOST="127.0.0.1"          # the server listens on the loopback address only (put a reverse proxy in front to publish it)

say()  { printf '%s\n' "$*"; }
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# ---------- environment -------------------------------------------------------

check_node() {
  command -v node >/dev/null 2>&1 || fail "Node.js is not installed. Install Node.js ${MIN_NODE_MAJOR}.${MIN_NODE_MINOR} or newer (https://nodejs.org)."
  local ver major minor
  ver="$(node -v 2>/dev/null | sed 's/^v//')"
  major="${ver%%.*}"; minor="${ver#*.}"; minor="${minor%%.*}"
  [[ "$major" =~ ^[0-9]+$ && "$minor" =~ ^[0-9]+$ ]] || fail "Could not read the Node.js version (\"$ver\")."
  if (( major < MIN_NODE_MAJOR || (major == MIN_NODE_MAJOR && minor < MIN_NODE_MINOR) )); then
    fail "Node.js ${MIN_NODE_MAJOR}.${MIN_NODE_MINOR}+ is required (found v$ver): the server uses the built-in node:sqlite module."
  fi
}

# Writes a default .env: sign-in required, local SQLite only.
write_default_env() {
  cat > "$ENV_FILE" <<'EOF'
# Kyrpy UI/UX Designer — settings (generated by runner.sh; edit freely)
PORT=5180
# release = sign-in required | dev = no sign-in, every visitor acts as the superadmin
APP_MODE=release
BYPASS_AUTH=false
# The server always works on its local SQLite database. PostgreSQL is an optional sync target
# (superadmin "Database sync" tool): set PG_SYNC_ENABLED=true and the PG* values to use it.
PG_SYNC_ENABLED=false
LOCAL_ONLY=true
PGHOST=
PGPORT=5432
PGUSER=postgres
PGPASSWORD=
PGDATABASE=kyrpy-uiux-designer-db
PGADMINDB=postgres
EOF
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  say "Created $ENV_FILE with the defaults (release mode, local SQLite only)."
}

# Reads KEY=VALUE lines without executing the file. A variable already set in the shell wins over the file.
load_env() {
  [ -f "$ENV_FILE" ] || return 0
  local line key val
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%$'\r'}"
    [[ "$line" =~ ^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*)[[:space:]]*=(.*)$ ]] || continue
    key="${BASH_REMATCH[2]}"; val="${BASH_REMATCH[3]}"
    val="${val#"${val%%[![:space:]]*}"}"; val="${val%"${val##*[![:space:]]}"}"
    if [[ "$val" == \"*\" && ${#val} -ge 2 ]] || [[ "$val" == \'*\' && ${#val} -ge 2 ]]; then val="${val:1:${#val}-2}"; fi
    [ -n "${!key+x}" ] || export "$key=$val"
  done < "$ENV_FILE"
}

# Local SQLite is the default: PostgreSQL sync stays off unless it was switched on explicitly and has a host.
apply_db_defaults() {
  local flag host
  flag="$(printf '%s' "${PG_SYNC_ENABLED:-}" | tr '[:upper:]' '[:lower:]')"
  host="${PGHOST:-${PG_HOST:-}}"
  if [[ ( "$flag" == "true" || "$flag" == "1" ) && -n "$host" ]]; then
    export PG_SYNC_ENABLED=true LOCAL_ONLY=false
  else
    export PG_SYNC_ENABLED=false LOCAL_ONLY=true
  fi
}

# Packages: the app has no runtime dependencies today; when package.json lists some, they are installed locally.
install_packages() {
  local need
  need="$(cd "$SRC_DIR" && node -e "const p=require('./package.json');process.stdout.write(Object.keys({...p.dependencies,...p.optionalDependencies}).length?'1':'0')" 2>/dev/null || echo 0)"
  [ "$need" = "1" ] || return 0
  [ -d "$SRC_DIR/node_modules" ] && [ "$SRC_DIR/node_modules" -nt "$SRC_DIR/package.json" ] && return 0
  command -v npm >/dev/null 2>&1 || fail "npm is needed to install the packages listed in src/package.json."
  say "Installing packages into src/node_modules ..."
  (cd "$SRC_DIR" && npm install --omit=dev --no-audit --no-fund) || fail "npm install failed."
}

# The bundled sample database: rebuilt from the SQL dump when the file is missing.
ensure_sample_db() {
  [ -n "${DESIGNER_DB_PATH:-}${DB_FILE:-}" ] && return 0                     # an explicit database is used as it is
  [ -f "$SRC_DIR/data/designer.prod.db" ] && return 0                         # the working database exists
  [ -f "$SRC_DIR/data/designer.db" ] && return 0                              # the server copies it on first start
  if [ -f "$ROOT_DIR/sql/sample_data_sqlite.sql" ]; then
    say "Building the sample database from sql/sample_data_sqlite.sql ..."
    mkdir -p "$SRC_DIR/data"
    (cd "$ROOT_DIR" && node "${NODE_FLAGS[@]}" --input-type=module -e "
      import { readFileSync } from 'node:fs';
      import { DatabaseSync } from 'node:sqlite';
      const db = new DatabaseSync('./src/data/designer.db');
      db.exec(readFileSync('./sql/sample_data_sqlite.sql', 'utf8'));
      db.close();
    ") || { rm -f "$SRC_DIR/data/designer.db"; fail "Could not build the sample database."; }
  else
    say "No sample database found: the server starts with an empty library and imports its built-in catalog."
  fi
}

prepare() {
  [ -f "$SRC_DIR/main.js" ] || fail "src/main.js not found: run this script from the project folder it ships in."
  check_node
  [ -f "$ENV_FILE" ] || write_default_env
  load_env
  PORT="${PORT:-5180}"
  [[ "$PORT" =~ ^[0-9]+$ ]] && (( PORT >= 1 && PORT <= 65535 )) || fail "PORT must be a number between 1 and 65535 (found \"$PORT\")."
  APP_MODE="${APP_MODE:-release}"
  BYPASS_AUTH="${BYPASS_AUTH:-false}"
  apply_db_defaults
  install_packages
  ensure_sample_db
}

# ---------- process helpers ---------------------------------------------------

port_in_use() {   # 0 when something answers on the port
  node -e "
    const s = require('node:net').connect({ host: '$SERVE_HOST', port: Number(process.argv[1]) });
    s.setTimeout(1500);
    s.on('connect', () => { s.destroy(); process.exit(0); });
    s.on('error', () => process.exit(1));
    s.on('timeout', () => { s.destroy(); process.exit(1); });
  " "$1" >/dev/null 2>&1
}

# The PID from the pid file, only while that process is still this server (a reused PID is not trusted).
running_pid() {
  [ -f "$PID_FILE" ] || return 1
  local pid args
  pid="$(tr -cd '0-9' < "$PID_FILE")"
  [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null || return 1
  args="$(ps -p "$pid" -o args= 2>/dev/null || true)"
  [[ "$args" == *"main.js serve"* ]] || return 1
  printf '%s' "$pid"
}

mode_env() {   # $1 = mode
  case "$1" in
    dev)     export APP_MODE=dev BYPASS_AUTH=true ;;
    release) export APP_MODE=release BYPASS_AUTH=false ;;
    *)       export APP_MODE="$APP_MODE" BYPASS_AUTH="$BYPASS_AUTH" ;;
  esac
  export PORT
}

print_ready() {
  say "Running -> http://${SERVE_HOST}:${PORT}   (mode: ${APP_MODE}, database: local SQLite$([ "$PG_SYNC_ENABLED" = "true" ] && printf ', PostgreSQL sync available to the superadmin'))"
  if [ "$BYPASS_AUTH" = "true" ] || [ "$APP_MODE" = "dev" ]; then
    say "Dev mode: no sign-in, every visitor acts as the superadmin. Do not expose this port."
  else
    say "Default accounts: superadmin / superadmin, admin / admin, user / user — change all three passwords after the first sign-in."
  fi
}

stop_bg() {
  local pid
  if ! pid="$(running_pid)"; then
    rm -f "$PID_FILE"
    return 1
  fi
  kill "$pid" 2>/dev/null || true
  for _ in $(seq 1 50); do kill -0 "$pid" 2>/dev/null || break; sleep 0.2; done
  if kill -0 "$pid" 2>/dev/null; then kill -9 "$pid" 2>/dev/null || true; sleep 0.3; fi
  rm -f "$PID_FILE"
  say "Stopped (PID $pid)."
}

start_bg() {   # $1 = mode ("" = from .env)
  local pid
  if pid="$(running_pid)"; then
    say "Already running (PID $pid) on http://${SERVE_HOST}:${PORT}. Use \"./runner.sh restart\" to restart it."
    return 0
  fi
  rm -f "$PID_FILE"
  # checked before anything is started: a second server on a busy port would open the database and then fail
  if port_in_use "$PORT"; then
    fail "Port $PORT is already in use by another program (maybe a server started another way). Stop it, or set another PORT in .env."
  fi
  mode_env "$1"
  say "Starting Kyrpy UI/UX Designer on http://${SERVE_HOST}:${PORT} ..."
  : > "$LOG_FILE"
  (
    cd "$SRC_DIR"
    nohup node "${NODE_FLAGS[@]}" main.js serve --port "$PORT" >> "$LOG_FILE" 2>&1 &
    echo $! > "$PID_FILE"
  )
  # ready = the process lives and the port answers (first start imports the sample library: allow it time)
  local waited=0
  while (( waited < 600 )); do
    if ! running_pid >/dev/null; then
      say "--- last lines of $LOG_FILE ---"; tail -n 20 "$LOG_FILE" 2>/dev/null || true
      rm -f "$PID_FILE"
      fail "The server stopped while starting. See the log above."
    fi
    if port_in_use "$PORT"; then print_ready; return 0; fi
    sleep 0.5; waited=$(( waited + 5 ))
  done
  say "--- last lines of $LOG_FILE ---"; tail -n 20 "$LOG_FILE" 2>/dev/null || true
  fail "The server did not answer on port $PORT within 60 s (it is still running as PID $(running_pid || echo '?'); see the log)."
}

run_fg() {
  if running_pid >/dev/null; then fail "A background server is running. Stop it first: ./runner.sh stop"; fi
  if port_in_use "$PORT"; then fail "Port $PORT is already in use by another program. Stop it, or set another PORT in .env."; fi
  mode_env ""
  print_ready
  cd "$SRC_DIR"
  exec node "${NODE_FLAGS[@]}" main.js serve --port "$PORT"
}

# ---------- commands ----------------------------------------------------------

CMD="${1:-start}"
case "$CMD" in
  start)        prepare; start_bg "" ;;
  run|fg)       prepare; run_fg ;;
  dev|release)  prepare; stop_bg >/dev/null 2>&1 || true; start_bg "$CMD" ;;
  restart)      prepare; stop_bg || true; start_bg "" ;;
  setup)        prepare; say "Environment ready. Start with: ./runner.sh start" ;;
  stop)         stop_bg || say "Not running." ;;
  status)
    load_env; PORT="${PORT:-5180}"
    if pid="$(running_pid)"; then
      if port_in_use "$PORT"; then say "Running (PID $pid) on http://${SERVE_HOST}:${PORT}"; else say "Process $pid is alive but port $PORT does not answer yet (starting, or PORT changed in .env)."; fi
    elif port_in_use "$PORT"; then
      say "Not started by this runner, but another program is listening on port $PORT."
    else
      say "Not running."
    fi
    ;;
  logs)         [ -f "$LOG_FILE" ] || fail "No log yet: start the server first."; exec tail -n 50 -f "$LOG_FILE" ;;
  -h|--help|help) sed -n '2,23p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' ;;
  *)            fail "Unknown command \"$CMD\". Use: start | run | dev | release | stop | restart | status | logs | setup" ;;
esac
