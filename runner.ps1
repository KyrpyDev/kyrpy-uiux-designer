# ==============================================================================
# Kyrpy UI/UX Designer — Runner (Windows PowerShell 5.1+ / PowerShell 7)
# ==============================================================================
# Works on a fresh clone: it prepares what the server needs (settings file, local
# database, packages) and then starts it. No installer run is required first.
#
#   .\runner.ps1            Start in the background (same as "start")
#   .\runner.ps1 start      Start in the background with the mode from .env
#   .\runner.ps1 run        Start in the foreground (Ctrl+C stops it)
#   .\runner.ps1 dev        (Re)start in Dev mode     - no sign-in, every visitor is the superadmin
#   .\runner.ps1 release    (Re)start in Release mode - sign-in required
#   .\runner.ps1 stop       Stop the background server
#   .\runner.ps1 restart    Stop, then start
#   .\runner.ps1 status     Is it running, on which port
#   .\runner.ps1 logs       Follow the server log
#   .\runner.ps1 setup      Prepare the environment only (no start)
#
# Database: the server always works on its local SQLite file (src\data\designer.prod.db,
# created from the bundled sample on first start). PostgreSQL is an optional sync target of
# the superadmin's "Database sync" tool and is OFF unless .env says PG_SYNC_ENABLED=true.
# ==============================================================================

param(
  [Parameter(Position = 0)][string]$Command = "start"
)

$ErrorActionPreference = "Stop"
$RootDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$SrcDir = Join-Path $RootDir "src"
$EnvFile = Join-Path $RootDir ".env"
$PidFile = Join-Path $RootDir ".designer-runner.pid"
$LogFile = Join-Path $RootDir "designer-runner.log"
$ErrFile = Join-Path $RootDir "designer-runner.err.log"
$ServeHost = "127.0.0.1"   # the server listens on the loopback address only
$MinNode = [version]"22.13.0"

function Fail([string]$Message) { Write-Host "ERROR: $Message" -ForegroundColor Red; exit 1 }

# ---------- environment -------------------------------------------------------

function Test-Node {
  if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Fail "Node.js is not installed. Install Node.js $($MinNode.Major).$($MinNode.Minor) or newer (https://nodejs.org)." }
  $raw = (& node -v).Trim().TrimStart('v')
  $ver = $null
  if (-not [version]::TryParse(($raw -replace '[^0-9.].*$', ''), [ref]$ver)) { Fail "Could not read the Node.js version (""$raw"")." }
  if ($ver -lt $MinNode) { Fail "Node.js $($MinNode.Major).$($MinNode.Minor)+ is required (found v$raw): the server uses the built-in node:sqlite module." }
}

function Write-DefaultEnv {
  $lines = @(
    "# Kyrpy UI/UX Designer - settings (generated by runner.ps1; edit freely)",
    "PORT=5180",
    "# release = sign-in required | dev = no sign-in, every visitor acts as the superadmin",
    "APP_MODE=release",
    "BYPASS_AUTH=false",
    "# The server always works on its local SQLite database. PostgreSQL is an optional sync target",
    "# (superadmin ""Database sync"" tool): set PG_SYNC_ENABLED=true and the PG* values to use it.",
    "PG_SYNC_ENABLED=false",
    "LOCAL_ONLY=true",
    "PGHOST=",
    "PGPORT=5432",
    "PGUSER=postgres",
    "PGPASSWORD=",
    "PGDATABASE=kyrpy-uiux-designer-db",
    "PGADMINDB=postgres"
  )
  # no byte order mark: the server reads this file too
  [System.IO.File]::WriteAllLines($EnvFile, $lines, (New-Object System.Text.UTF8Encoding($false)))
  Write-Host "Created $EnvFile with the defaults (release mode, local SQLite only)."
}

# Reads KEY=VALUE lines. A variable already set in the shell wins over the file.
function Import-Env {
  if (-not (Test-Path $EnvFile)) { return }
  foreach ($line in [System.IO.File]::ReadAllLines($EnvFile)) {
    if ($line -match '^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$') {
      $key = $matches[1]; $val = $matches[2].Trim()
      if ($val.Length -ge 2 -and (($val.StartsWith('"') -and $val.EndsWith('"')) -or ($val.StartsWith("'") -and $val.EndsWith("'")))) { $val = $val.Substring(1, $val.Length - 2) }
      if ($null -eq [System.Environment]::GetEnvironmentVariable($key, "Process")) { [System.Environment]::SetEnvironmentVariable($key, $val, "Process") }
    }
  }
}

# Local SQLite is the default: PostgreSQL sync stays off unless it was switched on explicitly and has a host.
function Set-DbDefaults {
  $flag = "$($env:PG_SYNC_ENABLED)".ToLower()
  $pgHost = if ($env:PGHOST) { $env:PGHOST } else { $env:PG_HOST }
  if (($flag -eq "true" -or $flag -eq "1") -and $pgHost) { $env:PG_SYNC_ENABLED = "true"; $env:LOCAL_ONLY = "false" }
  else { $env:PG_SYNC_ENABLED = "false"; $env:LOCAL_ONLY = "true" }
}

# Packages: the app has no runtime dependencies today; when package.json lists some, they are installed locally.
function Install-Packages {
  $pkg = Get-Content (Join-Path $SrcDir "package.json") -Raw | ConvertFrom-Json
  $count = 0
  foreach ($section in @("dependencies", "optionalDependencies")) {
    if ($pkg.PSObject.Properties.Name -contains $section -and $pkg.$section) { $count += @($pkg.$section.PSObject.Properties).Count }
  }
  if ($count -eq 0) { return }
  $modules = Join-Path $SrcDir "node_modules"
  if ((Test-Path $modules) -and ((Get-Item $modules).LastWriteTime -gt (Get-Item (Join-Path $SrcDir "package.json")).LastWriteTime)) { return }
  if (-not (Get-Command npm -ErrorAction SilentlyContinue)) { Fail "npm is needed to install the packages listed in src\package.json." }
  Write-Host "Installing packages into src\node_modules ..."
  Push-Location $SrcDir
  try { & npm install --omit=dev --no-audit --no-fund; if ($LASTEXITCODE -ne 0) { Fail "npm install failed." } } finally { Pop-Location }
}

# The bundled sample database: rebuilt from the SQL dump when the file is missing.
function Initialize-SampleDb {
  if ($env:DESIGNER_DB_PATH -or $env:DB_FILE) { return }
  $data = Join-Path $SrcDir "data"
  if ((Test-Path (Join-Path $data "designer.prod.db")) -or (Test-Path (Join-Path $data "designer.db"))) { return }
  $dump = Join-Path $RootDir "sql\sample_data_sqlite.sql"
  if (-not (Test-Path $dump)) { Write-Host "No sample database found: the server starts with an empty library and imports its built-in catalog."; return }
  Write-Host "Building the sample database from sql\sample_data_sqlite.sql ..."
  New-Item -ItemType Directory -Force -Path $data | Out-Null
  Push-Location $RootDir
  try {
    & node --disable-warning=ExperimentalWarning --input-type=module -e "import { readFileSync } from 'node:fs'; import { DatabaseSync } from 'node:sqlite'; const db = new DatabaseSync('./src/data/designer.db'); db.exec(readFileSync('./sql/sample_data_sqlite.sql', 'utf8')); db.close();"
    if ($LASTEXITCODE -ne 0) { Remove-Item (Join-Path $data "designer.db") -Force -ErrorAction SilentlyContinue; Fail "Could not build the sample database." }
  } finally { Pop-Location }
}

function Initialize-Environment {
  if (-not (Test-Path (Join-Path $SrcDir "main.js"))) { Fail "src\main.js not found: run this script from the project folder it ships in." }
  Test-Node
  if (-not (Test-Path $EnvFile)) { Write-DefaultEnv }
  Import-Env
  if (-not $env:PORT) { $env:PORT = "5180" }
  $p = 0
  if (-not [int]::TryParse($env:PORT, [ref]$p) -or $p -lt 1 -or $p -gt 65535) { Fail "PORT must be a number between 1 and 65535 (found ""$($env:PORT)"")." }
  if (-not $env:APP_MODE) { $env:APP_MODE = "release" }
  if (-not $env:BYPASS_AUTH) { $env:BYPASS_AUTH = "false" }
  Set-DbDefaults
  Install-Packages
  Initialize-SampleDb
}

# ---------- process helpers ---------------------------------------------------

function Test-Port([int]$Port) {
  $client = New-Object System.Net.Sockets.TcpClient
  try {
    $async = $client.BeginConnect($ServeHost, $Port, $null, $null)
    if (-not $async.AsyncWaitHandle.WaitOne(1500)) { return $false }
    $client.EndConnect($async)
    return $true
  } catch { return $false } finally { $client.Close() }
}

# The process from the pid file, only while it is still a node process (a reused PID is not trusted).
function Get-RunnerProcess {
  if (-not (Test-Path $PidFile)) { return $null }
  $id = 0
  if (-not [int]::TryParse((Get-Content $PidFile -Raw).Trim(), [ref]$id)) { return $null }
  $proc = Get-Process -Id $id -ErrorAction SilentlyContinue
  if ($proc -and $proc.ProcessName -like "node*") { return $proc }
  return $null
}

function Set-Mode([string]$Mode) {
  if ($Mode -eq "dev") { $env:APP_MODE = "dev"; $env:BYPASS_AUTH = "true" }
  elseif ($Mode -eq "release") { $env:APP_MODE = "release"; $env:BYPASS_AUTH = "false" }
}

function Write-Ready {
  $db = if ($env:PG_SYNC_ENABLED -eq "true") { "local SQLite, PostgreSQL sync available to the superadmin" } else { "local SQLite" }
  Write-Host "Running -> http://${ServeHost}:$($env:PORT)   (mode: $($env:APP_MODE), database: $db)" -ForegroundColor Green
  if ($env:BYPASS_AUTH -eq "true" -or $env:APP_MODE -eq "dev") { Write-Host "Dev mode: no sign-in, every visitor acts as the superadmin. Do not expose this port." -ForegroundColor Yellow }
  else { Write-Host "Default accounts: superadmin / superadmin, admin / admin, user / user - change all three passwords after the first sign-in." }
}

function Stop-Designer {
  $proc = Get-RunnerProcess
  if (-not $proc) { Remove-Item $PidFile -Force -ErrorAction SilentlyContinue; return $false }
  Stop-Process -Id $proc.Id -Force -ErrorAction SilentlyContinue
  try { $proc.WaitForExit(10000) | Out-Null } catch { }
  Remove-Item $PidFile -Force -ErrorAction SilentlyContinue
  Write-Host "Stopped (PID $($proc.Id))."
  return $true
}

function Start-Designer([string]$Mode) {
  $proc = Get-RunnerProcess
  if ($proc) { Write-Host "Already running (PID $($proc.Id)) on http://${ServeHost}:$($env:PORT). Use "".\runner.ps1 restart"" to restart it."; return }
  Remove-Item $PidFile -Force -ErrorAction SilentlyContinue
  # checked before anything is started: a second server on a busy port would open the database and then fail
  if (Test-Port ([int]$env:PORT)) { Fail "Port $($env:PORT) is already in use by another program (maybe a server started another way). Stop it, or set another PORT in .env." }
  Set-Mode $Mode
  Write-Host "Starting Kyrpy UI/UX Designer on http://${ServeHost}:$($env:PORT) ..."
  $nodeArgs = @("--disable-warning=ExperimentalWarning", "main.js", "serve", "--port", $env:PORT)
  $started = Start-Process -FilePath "node" -ArgumentList $nodeArgs -WorkingDirectory $SrcDir -PassThru -WindowStyle Hidden -RedirectStandardOutput $LogFile -RedirectStandardError $ErrFile
  Set-Content -Path $PidFile -Value $started.Id -Encoding ASCII
  # ready = the process lives and the port answers (first start imports the sample library: allow it time)
  for ($i = 0; $i -lt 120; $i++) {
    if ($started.HasExited) {
      Write-Host "--- last lines of the log ---"
      foreach ($f in @($LogFile, $ErrFile)) { if (Test-Path $f) { Get-Content $f -Tail 20 } }
      Remove-Item $PidFile -Force -ErrorAction SilentlyContinue
      Fail "The server stopped while starting. See the log above."
    }
    if (Test-Port ([int]$env:PORT)) { Write-Ready; return }
    Start-Sleep -Milliseconds 500
  }
  Fail "The server did not answer on port $($env:PORT) within 60 s (it is still running as PID $($started.Id); see $LogFile)."
}

function Start-Foreground {
  if (Get-RunnerProcess) { Fail "A background server is running. Stop it first: .\runner.ps1 stop" }
  if (Test-Port ([int]$env:PORT)) { Fail "Port $($env:PORT) is already in use by another program. Stop it, or set another PORT in .env." }
  Write-Ready
  Push-Location $SrcDir
  try { & node --disable-warning=ExperimentalWarning main.js serve --port $env:PORT } finally { Pop-Location }
}

# ---------- commands ----------------------------------------------------------

switch ($Command.ToLower()) {
  "start"   { Initialize-Environment; Start-Designer "" }
  "run"     { Initialize-Environment; Start-Foreground }
  "fg"      { Initialize-Environment; Start-Foreground }
  "dev"     { Initialize-Environment; Stop-Designer | Out-Null; Start-Designer "dev" }
  "release" { Initialize-Environment; Stop-Designer | Out-Null; Start-Designer "release" }
  "restart" { Initialize-Environment; Stop-Designer | Out-Null; Start-Designer "" }
  "setup"   { Initialize-Environment; Write-Host "Environment ready. Start with: .\runner.ps1 start" }
  "stop"    { if (-not (Stop-Designer)) { Write-Host "Not running." } }
  "status"  {
    Import-Env
    if (-not $env:PORT) { $env:PORT = "5180" }
    $proc = Get-RunnerProcess
    $answers = Test-Port ([int]$env:PORT)
    if ($proc -and $answers) { Write-Host "Running (PID $($proc.Id)) on http://${ServeHost}:$($env:PORT)" -ForegroundColor Green }
    elseif ($proc) { Write-Host "Process $($proc.Id) is alive but port $($env:PORT) does not answer yet (starting, or PORT changed in .env)." -ForegroundColor Yellow }
    elseif ($answers) { Write-Host "Not started by this runner, but another program is listening on port $($env:PORT)." -ForegroundColor Yellow }
    else { Write-Host "Not running." }
  }
  "logs"    { if (-not (Test-Path $LogFile)) { Fail "No log yet: start the server first." }; Get-Content $LogFile -Tail 50 -Wait }
  default   { Fail "Unknown command ""$Command"". Use: start | run | dev | release | stop | restart | status | logs | setup" }
}
